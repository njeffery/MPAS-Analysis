from mpas_analysis.shared import AnalysisTask

from mpas_analysis.shared.climatology import RemapMpasClimatologySubtask

from mpas_analysis.shared.plot import PlotClimatologyMapSubtask


class ClimatologyMapSeaIceAerosolImpurities(AnalysisTask):
    """
    An analysis task for plotting seasonal climatologies of sea-ice dust and
    black carbon burden fields in polar stereographic projections.
    """

    # Authors
    # -------
    # Generated by Copilot adaptation

    def __init__(self, config, mpas_climatology_task, hemisphere,
                 control_config=None):
        """
        Construct the analysis task.

        Parameters
        ----------
        config : tranche.Tranche
            Configuration options

        mpas_climatology_task : ``MpasClimatologyTask``
            The task that produced the climatology to be remapped and plotted

        hemisphere : {'NH', 'SH'}
            The hemisphere to plot

        control_config : tranche.Tranche, optional
            Configuration options for a control run (if any)
        """
        task_name = f'climatologyMapSeaIceAerosolImpurities{hemisphere}'

        tags = ['climatology', 'horizontalMap', 'BGC', 'seaiceAerosols']
        if hemisphere == 'NH':
            tags.append('arctic')
        else:
            tags.append('antarctic')

        super().__init__(config=config, taskName=task_name,
                         componentName='seaIce', tags=tags)

        section_name = self.taskName
        hemisphere_long = 'Northern' if hemisphere == 'NH' else 'Southern'

        seasons = config.getexpression(section_name, 'seasons')
        if len(seasons) == 0:
            raise ValueError(f'config section {section_name} does not contain '
                             'valid list of seasons')

        comparison_grid_names = config.getexpression(section_name,
                                                     'comparisonGrids')
        if len(comparison_grid_names) == 0:
            raise ValueError(f'config section {section_name} does not contain '
                             'valid list of comparison grids')

        variable_specs = [
            {'field': 'totalVerticalDustSnow',
             'title': 'Total vertical dust in snow',
             'units': r'mg m$^{-2}$',
             'factor': 1.0e6,
             'config_section': 'seaIceDustImpurity'},
            {'field': 'totalVerticalDustIce',
             'title': 'Total vertical dust in ice',
             'units': r'mg m$^{-2}$',
             'factor': 1.0e6,
             'config_section': 'seaIceDustImpurity'},
            {'field': 'totalVerticalBCSnow',
             'title': 'Total vertical BC in snow',
             'units': r'ng g$^{-1}$',
             'factor': 3.030303e6,
             'config_section': 'seaIceBCImpurity'},
            {'field': 'totalVerticalBCIce',
             'title': 'Total vertical BC in ice',
             'units': r'ng g$^{-1}$',
             'factor': 3.030303e6,
             'config_section': 'seaIceBCImpurity'}
        ]

        for spec in variable_specs:
            field_name = spec['field']
            mpas_field_name = f'timeMonthly_avg_{field_name}'

            remap_climatology_subtask = RemapMpasSeaIceImpurityClimatology(
                mpas_climatology_task=mpas_climatology_task,
                parent_task=self,
                climatology_name=f'{field_name}{hemisphere}',
                variable_list=[mpas_field_name],
                comparison_grid_names=comparison_grid_names,
                seasons=seasons,
                conversion_factor=spec['factor'])

            ref_title_label = None
            ref_field_name = None
            diff_title_label = None
            if control_config is not None:
                control_run_name = control_config.get('runs', 'mainRunName')
                ref_title_label = f'Control: {control_run_name}'
                ref_field_name = mpas_field_name
                diff_title_label = 'Main - Control'

            for comparison_grid_name in comparison_grid_names:
                for season in seasons:
                    subtask_name = \
                        f'plot_{field_name}_{season}_{comparison_grid_name}'
                    subtask = PlotClimatologyMapSubtask(
                        parentTask=self, season=season,
                        comparisonGridName=comparison_grid_name,
                        remapMpasClimatologySubtask=remap_climatology_subtask,
                        remapObsClimatologySubtask=None,
                        controlConfig=control_config,
                        subtaskName=subtask_name)

                    image_caption = (
                        f'Climatology map of {hemisphere_long}-hemisphere '
                        f'{spec["title"].lower()}')

                    subtask.set_plot_info(
                        outFileLabel=f'{field_name}{hemisphere}',
                        fieldNameInTitle=spec['title'],
                        mpasFieldName=mpas_field_name,
                        refFieldName=ref_field_name,
                        refTitleLabel=ref_title_label,
                        diffTitleLabel=diff_title_label,
                        unitsLabel=spec['units'],
                        imageCaption=image_caption,
                        galleryGroup=f'BGC - {hemisphere_long}-Hemisphere '
                                     'Sea-Ice Aerosol Impurities',
                        groupSubtitle=None,
                        groupLink=f'{hemisphere.lower()}_sea_ice_impurities',
                        galleryName=spec['title'],
                        configSectionName=spec['config_section'],
                        prependComparisonGrid=False)

                    self.add_subtask(subtask)


class RemapMpasSeaIceImpurityClimatology(RemapMpasClimatologySubtask):
    """
    A subtask for converting sea-ice impurity fields to requested plotting
    units after climatology masking and prior to remapping.
    """

    def __init__(self, mpas_climatology_task, parent_task, climatology_name,
                 variable_list, seasons, comparison_grid_names,
                 conversion_factor):

        super().__init__(
            mpasClimatologyTask=mpas_climatology_task,
            parentTask=parent_task,
            climatologyName=climatology_name,
            variableList=variable_list,
            comparisonGridNames=comparison_grid_names,
            seasons=seasons,
            iselValues=None,
            subtaskName=f'remap_{climatology_name}')

        self.conversion_factor = conversion_factor

    def customize_masked_climatology(self, climatology, season):
        """
        Apply a scalar conversion to the mapped variable.
        """
        climatology = super().customize_masked_climatology(climatology, season)

        variable = self.variableList[0]
        climatology[variable] = climatology[variable] * self.conversion_factor
        return climatology